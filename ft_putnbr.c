#include "ft_printf.h"

void	ft_putnbr(int n)
{
	long	ln;
	char	num;

	ln = n;
	if (n < 0)
	{
		write(1, "-", 1);
		ln *= (-1);
	}
	if ((ln / 10) != 0)
		ft_putnbr (ln / 10);
	num = (ln % 10) + '0';
	write(1, &num, 1);
}
